/** How each tray looks in the top bar. */
const TRAYS: Record<NotificationTray, { label: string; icon: string; empty: string; hideWhenEmpty: boolean }> = {
  bell: { label: 'Notifications', icon: 'bell', empty: "You're all caught up.", hideWhenEmpty: false },
  subtitleSync: { label: 'Subtitle syncs', icon: 'sync', empty: 'No subtitle syncs.', hideWhenEmpty: true },
};

/**
 * An icon in the top bar (the bell by default) with a badge showing the total and a panel listing the notifications
 * of its tray, each linking to its page. The subtitle sync tray only shows while it has something, and its icon spins
 * while a sync is waiting or running.
 */
@Component({
  selector: 'kr-notification-bell',
  imports: [RouterLink],
  host: {
    class: 'relative inline-block',
    '[class.hidden]': 'hidden()',
    '(document:click)': 'onDocumentClick($event)',
    '(document:keydown.escape)': 'open.set(false)',
  },
  templateUrl: './notification-bell.html',
  styleUrl: './notification-bell.scss',
})
export class NotificationBell {
  protected readonly notifications = inject(Notifications);
  private readonly host = inject<ElementRef<HTMLElement>>(ElementRef);
  protected readonly icons = KIND_ICONS;
  protected readonly open = signal(false);
  readonly tray = input<NotificationTray>('bell');
  protected readonly config = computed(() => TRAYS[this.tray()]);
  protected readonly state = computed(() => this.notifications.tray(this.tray()));

  /** Trays that hide when empty stay visible while their panel is open, so dismissing the last item doesn't yank it away. */
  protected readonly hidden = computed(() => this.config().hideWhenEmpty && this.state().items().length === 0 && !this.open());

  protected label() {
    const total = this.state().total();
    const label = this.config().label;
    return total === 0 ? label : `${label} (${total})`;
  }

  protected tone(n: AppNotification) {
    return n.severity === 'Error' ? 'text-rose-400' : n.severity === 'Warning' ? 'text-amber-400'
      : n.severity === 'Success' ? 'text-emerald-400' : 'text-accent-300';
  }

  /** Estimated time left as "45 s left", "3 min left" or "1 h 5 min left"; empty without an estimate. */
  protected remaining(seconds: number | null | undefined): string {
    if (seconds == null) return '';
    if (seconds < 60) return `${Math.max(1, Math.ceil(seconds))} s left`;
    const minutes = Math.ceil(seconds / 60);
    if (minutes < 60) return `${minutes} min left`;
    const rest = minutes % 60;
    return `${Math.floor(minutes / 60)} h${rest ? ` ${rest} min` : ''} left`;
  }

  protected onDocumentClick(event: MouseEvent) {
    if (this.open() && !event.composedPath().includes(this.host.nativeElement)) this.open.set(false);
  }
}
